#!/usr/bin/env python3
"""Write recorded conditions for the three reported passes, without changing rows.

    nice -n 19 python scripts/conditions-table.py

Only results/analysis/conditions-<machine>-<pass>.{md,tex} are written. Different
conditions within a row family get separate entries; absent fields stay unknown.
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PASSES = ("ws-amd/2026-09-05", "ws-nvidia/2026-09-05", "hpc-a30/2026-09-17")
PREFIXES = ("OMP_", "GOMP_", "KMP_", "DPCPP_", "MKL_", "OPENBLAS_", "TBB_", "BLIS_", "NUMEXPR_")


def recorded(row):
    si = row.get("sysinfo") or {}
    env = si.get("env") or {}
    cpu = si.get("cpu") or {}
    build = dict(row.get("build_info") or {})
    return {
        "Backend / selected BLAS": {"backend": row.get("backend"), "blas": row.get("blas")},
        "Environment": {k: v for k, v in sorted(env.items())
                        if k.startswith(PREFIXES) or k == "LD_LIBRARY_PATH" or "THREAD" in k},
        "Loaded libraries (sysinfo.libs)": sorted(si.get("libs") or []),
        "Thread counts": {"threads_requested": row.get("threads"),
                          "threads_effective": row.get("threads_effective"),
                          "omp_max_threads": si.get("omp_max_threads")},
        "CPU affinity": {"affinity_count": cpu.get("affinity"), "cpuset_effective": cpu.get("cpuset_effective"),
                         "model": cpu.get("model")},
        "NUMA (sysinfo.numa)": si.get("numa") or {},
        "Compiler / flags / build": build,
        "Library version": {"build_info.version": build.get("version"),
                            "installed_package": (si.get("packages") or {}).get(row.get("backend"))},
    }


def lines(value):
    if isinstance(value, dict):
        return [f"{k}: {json.dumps(v, sort_keys=True) if isinstance(v, (dict, list)) else v if v is not None else 'not recorded'}"
                for k, v in value.items()] or ["not recorded"]
    return list(value) or ["not recorded"]


def tex(s):
    escapes = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
               "_": r"\_\allowbreak{}", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(escapes.get(c, c + r"\allowbreak{}" if c == "/" else c) for c in str(s))


def source_ranges(sources):
    files = defaultdict(list)
    for source in sources:
        name, number = source.rsplit(":", 1)
        files[name].append(int(number))
    result = []
    for name, numbers in sorted(files.items()):
        spans = []
        start = end = numbers[0]
        for n in numbers[1:]:
            if n == end + 1:
                end = n
            else:
                spans.append(str(start) if start == end else f"{start}–{end}")
                start = end = n
        spans.append(str(start) if start == end else f"{start}–{end}")
        result.append(f"{name}: " + ", ".join(spans))
    return result


def generate(pass_name):
    root = ROOT / "results" / pass_name
    groups = defaultdict(lambda: defaultdict(list))
    for path in sorted(root.rglob("*.jsonl")):
        if path.name == "superseded.jsonl":
            continue
        for number, line in enumerate(path.read_text().splitlines(), 1):
            if not line.strip():
                continue
            row = json.loads(line)
            signature = json.dumps(recorded(row), sort_keys=True)
            family = str(path.parent.relative_to(root))
            groups[family][signature].append(f"{path.name}:{number}")
    intro = ("Recorded conditions of live rows, grouped by directory and identical recorded conditions. "
             "Superseded rows are excluded. Loaded libraries are mappings, not proof that every mapped BLAS was called; "
             "NumPy's private scipy_openblas library is listed separately by its path. Thread counts are runtime limits, "
             "not measurements of BLAS worker activity. CPU affinity/NUMA fields describe the recording thread; "
             "they do not establish every worker's placement. Missing fields mean not recorded.")
    md = [f"# Recorded conditions: {pass_name}\n", intro + "\n"]
    latex = ["% Requires longtable and array. Generated by scripts/conditions-table.py.\n",
             r"\begingroup\small" + "\n", tex(intro) + "\n\n"]
    for family, variants in sorted(groups.items()):
        for index, (signature, sources) in enumerate(sorted(variants.items()), 1):
            title = f"{family} — conditions {index}, {len(sources)} rows"
            fields = json.loads(signature)
            fields["Source rows"] = source_ranges(sources)
            md += [f"\n## {title}\n", "| Field | Recorded value |\n|---|---|\n"]
            latex += [r"\begin{longtable}{>{\raggedright\arraybackslash}p{0.23\linewidth}>{\raggedright\arraybackslash}p{0.71\linewidth}}" + "\n",
                      r"\multicolumn{2}{l}{\textbf{" + tex(title) + r"}} \\" + "\n"]
            for key, value in fields.items():
                values = lines(value)
                md.append(f"| {key} | " + "<br>".join(v.replace("|", "\\|").replace("\n", " ") for v in values) + " |\n")
                latex.append(tex(key) + " & " + r"\newline ".join(tex(v) for v in values) + r" \\" + "\n")
            latex.append("\\end{longtable}\n")
    latex.append("\\endgroup\n")
    out = ROOT / "results" / "analysis"
    out.mkdir(parents=True, exist_ok=True)
    name = "conditions-" + pass_name.replace("/", "-")
    for suffix, content in (("md", md), ("tex", latex)):
        path = out / f"{name}.{suffix}"
        path.write_text("".join(content))
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    for name in PASSES:
        generate(name)
