#!/usr/bin/env bash
# Run on ws-nvidia only, after bench mode is on.
# Every process uses node 1. Only this script's labelled fnn-extra containers are managed.
set -uo pipefail
B=$(cd "$(dirname "$0")/.." && pwd); AC=$(dirname "$B")
ACTION=${1:-}; DATE=${2:-$(date +%F)}
[[ $DATE =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]] || exit 2
TOOLS=results/ws-nvidia/extra-tools-$DATE
mkdir -p "$B/$TOOLS/data" "$B/$TOOLS/ref"
ACTIVE=""
cleanup() {
    if [ -n "$ACTIVE" ] && podman container exists "$ACTIVE"; then
        owner=$(podman inspect --format '{{index .Config.Labels "fnn.extra.owner"}}' "$ACTIVE")
        [ "$owner" != workstation-extras ] || podman stop --time 5 "$ACTIVE" >/dev/null
    fi
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
run() { # run image wheel command; repos are read-only except the benchmark workspace
    local image=$1 wheel=$2; shift 2
    [ ! -f "$B/$TOOLS/CANCELLED" ] || return 130
    ACTIVE=fnn-extra-$ACTION-$$-$RANDOM
    podman run --rm --name "$ACTIVE" --label fnn.extra.owner=workstation-extras --label "fnn.extra.date=$DATE" \
        --memory=40g --device nvidia.com/gpu=all --security-opt=label=disable \
        -v "$AC/cudann:/work/cudann:ro" -v "$AC/syclnn:/work/syclnn:ro" -v "$AC/ompnn:/work/ompnn:ro" \
        -v "$B:/work/fnn-bench" -w /work/fnn-bench \
        -e FNN_MACHINE_ID=ws-nvidia -e PYTHONDONTWRITEBYTECODE=1 -e PYTHONPATH="/work/fnn-bench/bench:/work/fnn-bench/testkit:/work/fnn-bench/.wheels/ws-nvidia-$wheel" \
        -e FNN_REF_CACHE="/work/fnn-bench/$TOOLS/ref" -e FNN_DATA_DIR="/work/fnn-bench/$TOOLS/data" \
        "localhost/$image:dev" numactl --cpunodebind=1 --membind=1 bash -c "$*"
    local code=$?; ACTIVE=""; return "$code"
}
prepare() {
    local exp=$1; R=results/ws-nvidia/$exp-$DATE; mkdir -p "$B/$R"
    printf '%s\n' 'other services were running on the host and in the VM, as in every ws-nvidia pass; their CPU and GPU use is not controlled' 'The GPU was not dedicated to the benchmark.' > "$B/$R/background-host.txt"
    [ ! -f "$B/$TOOLS/bench-mode-status.txt" ] || python3 -c 'import sys; sys.path.insert(0, "scripts"); from extra_conditions import public_bench_status; print(public_bench_status(open(sys.argv[1]).read()), end="")' "$B/$TOOLS/bench-mode-status.txt" > "$B/$R/bench-mode-status.txt"
    run fnn-cuda cuda "python scripts/extra_conditions.py $R --machine ws-nvidia --binding 'numactl --cpunodebind=1 --membind=1'" || return 1
    printf 'bash scripts/ws-nvidia-extras.sh %s %s\n' "$ACTION" "$DATE" > "$B/$R/commands.txt"
}
# Check by image as well as name: the existing matrix uses autogenerated names.
if podman ps --format '{{.Image}} {{.Names}}' | grep -Eq '(^|/)fnn-[^ ]*:| fnn-'; then
    echo 'WAIT: another fnn container is running'; exit 75
fi
case "$ACTION" in
sanitizer)
    prepare sanitizer || exit 1
    run fnn-cuda cuda "python scripts/fetch-sanitizer.py $R" > "$B/$R/tool-setup.log" 2>&1 || exit 1
    san=$(cat "$B/$R/sanitizer-path.txt")
    for tool in memcheck racecheck synccheck initcheck; do
        run fnn-cuda cuda "python scripts/sanitizer-cases.py --tool $tool --sanitizer '$san' --out $R" > "$B/$R/$tool-progress.log" 2>&1 || true
    done
    ;;
stream)
    prepare stream || exit 1
    run fnn-cuda cuda "nvcc --version; python --version" > "$B/$R/versions.txt" 2>&1
    printf '%s\n' 'nvcc -O3 -std=c++17 -arch=sm_61 -ccbin g++-13 scripts/stream-probe.cu -o stream-probe' './stream-probe (384 MiB, 31 repetitions)' >> "$B/$R/commands.txt"
    run fnn-cuda cuda "nvcc -O3 -std=c++17 -arch=sm_61 -ccbin g++-13 scripts/stream-probe.cu -o $R/stream-probe && $R/stream-probe > $R/stream.csv && python scripts/stream-table.py $R" > "$B/$R/run.log" 2>&1 || exit 1
    ;;
nsys-epoch)
    prepare nsys-epoch || exit 1
    run fnn-cuda cuda "g++-13 -O2 -shared -fPIC -I/usr/local/cuda-12.9/include scripts/nvtx-range.cpp -ldl -o $R/nvtx-range.so" || exit 1
    for cfg in 'fnn-cuda cuda cudann' 'fnn-sycl sycl syclnn' 'fnn-cuda omp-clang18nv ompnn'; do
        read -r img wheel be <<< "$cfg"
        for state in off on; do
            opt=""; [ "$state" = on ] && opt=--profile
            tag=$be-$state
            run "$img" "$wheel" "python scripts/nsys-captures.py --backend $be --state $state --out $R" > "$B/$R/$tag-progress.log" 2>&1 || true
        done
    done
    cat "$B/$R/"*-version.txt > "$B/$R/versions.txt"
    run fnn-cuda cuda "python scripts/nsys-epoch-table.py $R" || exit 1
    ;;
counter-check)
    prepare gemm-counters || exit 1
    run fnn-cuda cuda "python scripts/nvidia-counter-check.py --out $R --tools $TOOLS/profilers" > "$B/$R/check-progress.log" 2>&1
    ;;
counter-memory)
    R=results/ws-nvidia/gemm-counters-$DATE
    nvprof=$(cat "$B/$TOOLS/profilers/nvprof-path.txt")
    cmd="'$nvprof' --profile-from-start off --kernels '.*gemm.*' --metrics dram_read_bytes,dram_write_bytes --print-gpu-trace --csv --log-file $R/diagnostics/memory.csv python scripts/nsys_epoch.py --backend cudann --blas tiled --samples 256 --batch 256 --epochs 1 --out $R/diagnostics/memory-driver.json"
    printf '%s\n' "$cmd" > "$B/$R/diagnostics/memory-command.txt"
    run fnn-cuda cuda "$cmd" > "$B/$R/diagnostics/memory.log" 2>&1
    printf '%s\n' "$?" > "$B/$R/diagnostics/memory.exit"
    ;;
counter-api)
    R=results/ws-nvidia/gemm-counters-$DATE
    run fnn-cuda cuda "python scripts/cuda-access-check.py --counter" > "$B/$R/diagnostics/cupti-event-api.json" 2> "$B/$R/diagnostics/cupti-event-api.log"
    ;;
diagnostics)
    R=results/ws-nvidia/gemm-counters-$DATE
    S=results/ws-nvidia/sanitizer-$DATE
    mkdir -p "$B/$R/diagnostics" "$B/$S/diagnostics"
    run fnn-cuda cuda "python scripts/cuda-access-check.py > $R/diagnostics/native.json; readlink -f /usr/lib/x86_64-linux-gnu/libcuda.so /usr/lib/x86_64-linux-gnu/libcuda.so.1; ldconfig -p | grep -E 'libcuda|libcupti'" > "$B/$R/diagnostics/loader.log" 2>&1
    nvprof=$(cat "$B/$TOOLS/profilers/nvprof-path.txt")
    run fnn-cuda cuda "'$nvprof' --query-metrics" > "$B/$R/diagnostics/nvprof-query.log" 2>&1 || true
    run fnn-cuda cuda "'$nvprof' --profile-from-start off python scripts/cuda-access-check.py" > "$B/$R/diagnostics/nvprof-native.log" 2>&1 || true
    san=$(cat "$B/$S/sanitizer-path.txt")
    run fnn-cuda cuda "nvcc -O2 -std=c++17 -arch=sm_61 -ccbin g++-13 scripts/cublas-race-probe.cu -lcublas -o $S/diagnostics/cublas-race-probe && '$san' --tool racecheck --error-exitcode 86 --print-limit 20 $S/diagnostics/cublas-race-probe" > "$B/$S/diagnostics/cublas-only-racecheck.log" 2>&1
    printf '%s\n' "$?" > "$B/$S/diagnostics/cublas-only-exit.txt"
    run fnn-cuda cuda "python scripts/sanitizer-cases.py --report-only --out $S"
    ;;
stat-confirm)
    prepare stat-confirm || exit 1
    run fnn-cuda cuda "python --version; python -m pip show numpy" > "$B/$R/versions.txt" 2>&1
    for round in 1 2 3; do
        order='cudann syclnn'; cup='default in-order graph'
        [ "$round" = 2 ] && { order='syclnn cudann'; cup='graph in-order default'; }
        for batch in 256 1024; do for be in $order; do
            img=fnn-cuda; wheel=cuda; [ "$be" = syclnn ] && { img=fnn-sycl; wheel=sycl; }
            run "$img" "$wheel" "python scripts/stat-confirm.py --source results/ws-nvidia/2026-09-05/gpu-cuda-vs-sycl --run $be-mnist-b$batch --round $round --out $R" || true
        done; done
        for opt in $cup; do
            run fnn-cuda cuda "python scripts/stat-confirm.py --source results/ws-nvidia/2026-09-05/gpu-cuda-vs-sycl --run cudann-cup-$opt --round $round --out $R" || true
        done
    done
    run fnn-cuda cuda "python scripts/stat-confirm.py --out $R"
    ;;
*) echo 'expected sanitizer, stream, nsys-epoch, counter-check or stat-confirm'; exit 2 ;;
esac
